const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('launcher', {
  list: (force) => ipcRenderer.invoke('games:list', force),
  launch: (id) => ipcRenderer.invoke('games:launch', id),
  add: () => ipcRenderer.invoke('games:add'),
  remove: (id) => ipcRenderer.invoke('games:remove', id),
  uninstall: (id) => ipcRenderer.invoke('games:uninstall', id),
  stats: () => ipcRenderer.invoke('stats:get'),
  savesInfo: (id) => ipcRenderer.invoke('saves:info', id),
  backupSaves: (id) => ipcRenderer.invoke('saves:backup', id),
  restoreSaves: (id, dir) => ipcRenderer.invoke('saves:restore', id, dir),
  pickSavesFolder: (id, clear) => ipcRenderer.invoke('saves:pickFolder', id, clear),
  openSavesFolder: (id) => ipcRenderer.invoke('saves:openFolder', id),
  pickSavesDir: () => ipcRenderer.invoke('settings:pickSavesDir'),
  setAutoBackup: (on) => ipcRenderer.invoke('settings:setAutoBackup', on),
  changeExe: (id) => ipcRenderer.invoke('games:changeExe', id),
  search: (term) => ipcRenderer.invoke('games:search', term),
  setMatch: (id, provider, ref, name) => ipcRenderer.invoke('games:setMatch', id, provider, ref, name),
  achievements: (id) => ipcRenderer.invoke('games:achievements', id),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSgdbKey: (key) => ipcRenderer.invoke('settings:setSgdbKey', key),
  openSgdbKeyPage: () => ipcRenderer.invoke('settings:openSgdbKeyPage'),
  setSteamKey: (key) => ipcRenderer.invoke('settings:setSteamKey', key),
  openSteamKeyPage: () => ipcRenderer.invoke('settings:openSteamKeyPage'),
  rename: (id, name) => ipcRenderer.invoke('games:rename', id, name),
  pickCover: (id) => ipcRenderer.invoke('games:pickCover', id),
  openFolder: (id) => ipcRenderer.invoke('games:openFolder', id),
  categories: () => ipcRenderer.invoke('categories:list'),
  createCategory: (name) => ipcRenderer.invoke('categories:create', name),
  renameCategory: (id, name) => ipcRenderer.invoke('categories:rename', id, name),
  deleteCategory: (id) => ipcRenderer.invoke('categories:delete', id),
  setGameCategory: (id, gameId, on) => ipcRenderer.invoke('categories:setGame', id, gameId, on),
  importSteamCategories: () => ipcRenderer.invoke('categories:importSteam'),
  minimizeWindow: () => ipcRenderer.invoke('window:minimize'),
  toggleMaximizeWindow: () => ipcRenderer.invoke('window:toggleMaximize'),
  setFullScreen: (on) => ipcRenderer.invoke('window:setFullScreen', on),
  closeWindow: () => ipcRenderer.invoke('window:close'),
  isWindowMaximized: () => ipcRenderer.invoke('window:isMaximized'),
  onWindowMaximized: (callback) => ipcRenderer.on('window:maximized', (_event, maximized) => callback(maximized)),
  setHidden: (id, hidden) => ipcRenderer.invoke('games:setHidden', id, hidden),
  connectAccount: (store) => ipcRenderer.invoke('accounts:connect', store),
  disconnectAccount: (store) => ipcRenderer.invoke('accounts:disconnect', store),
  accent: (id) => ipcRenderer.invoke('games:accent', id),
  downloads: () => ipcRenderer.invoke('downloads:list'),
  addDownload: (text, useRd) => ipcRenderer.invoke('downloads:add', { text, useRd }),
  addTorrentFile: (useRd) => ipcRenderer.invoke('downloads:addTorrentFile', { useRd }),
  downloadFiles: (id) => ipcRenderer.invoke('downloads:files', id),
  selectDownloadFiles: (id, indexes) => ipcRenderer.invoke('downloads:selectFiles', id, indexes),
  setCloseToTray: (on) => ipcRenderer.invoke('settings:setCloseToTray', on),
  setOpenAtLogin: (on) => ipcRenderer.invoke('settings:setOpenAtLogin', on),
  pauseDownload: (id) => ipcRenderer.invoke('downloads:pause', id),
  resumeDownload: (id) => ipcRenderer.invoke('downloads:resume', id),
  removeDownload: (id) => ipcRenderer.invoke('downloads:remove', id),
  openDownloadFolder: (id) => ipcRenderer.invoke('downloads:openFolder', id),
  addDownloadToLibrary: (id) => ipcRenderer.invoke('downloads:addToLibrary', id),
  downloadHistory: () => ipcRenderer.invoke('downloads:history'),
  onDownloads: (callback) => ipcRenderer.on('downloads:update', (_event, list, history) => callback(list, history)),
  sources: () => ipcRenderer.invoke('sources:list'),
  addSourceUrl: (url) => ipcRenderer.invoke('sources:addUrl', url),
  addSourceFile: () => ipcRenderer.invoke('sources:addFile'),
  refreshSource: (id) => ipcRenderer.invoke('sources:refresh', id),
  removeSource: (id) => ipcRenderer.invoke('sources:remove', id),
  searchSources: (term, only) => ipcRenderer.invoke('sources:search', term, only),
  downloadFromSource: (item, useRd) => ipcRenderer.invoke('sources:download', { source: item.source, index: item.index, title: item.title, useRd }),
  onSources: (callback) => ipcRenderer.on('sources:changed', () => callback()),
  pickDownloadDir: () => ipcRenderer.invoke('settings:pickDownloadDir'),
  setRdToken: (token) => ipcRenderer.invoke('settings:setRdToken', token),
  openRdTokenPage: () => ipcRenderer.invoke('settings:openRdTokenPage'),
  onChanged: (callback) => ipcRenderer.on('games:changed', () => callback()),
});
